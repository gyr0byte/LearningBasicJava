public class DoWhileLoop {
    public static void main(String[] args) {
        int i = 1;
          do{
             System.out.print(i+" ");
             i++;
          }while(i<=10);
          i--;
          System.out.println();
          do{
            System.out.print(i+" ");
            i--;
          }while(i>0);
    }
    
}
