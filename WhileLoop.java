public class WhileLoop {
    public static void main(String[] args) {
        int i = 1;
        while (i <= 10) {
            System.out.print(i + " ");
            i++;
        }
        int j = 10;
        System.out.println();
        while (j > 0) {
            System.out.print(j + " ");
            j--;
        }
    }
}
